"""Write syncmily/_emoji_data.py from the Unicode 15.1 data files.

Run it by hand when Syncmily moves to a newer Unicode version. Download the two
files first, then pass their paths:

    curl -O https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt
    curl -O https://www.unicode.org/Public/15.1.0/ucd/DerivedCoreProperties.txt
    python scripts/gen_emoji_data.py emoji-data.txt DerivedCoreProperties.txt

The app itself never downloads anything: it imports the generated table.
"""

import re
import sys
from pathlib import Path

SOURCES = (
    "https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt",
    "https://www.unicode.org/Public/15.1.0/ucd/DerivedCoreProperties.txt",
)
LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")
OUT = Path(__file__).resolve().parent.parent / "syncmily" / "_emoji_data.py"


def ranges(path, prop):
    """Sorted, merged (first, last) code point ranges that have the property."""
    found = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        match = LINE.match(line)
        if match and match.group(3) == prop:
            first = int(match.group(1), 16)
            found.append((first, int(match.group(2) or match.group(1), 16)))
    merged = []
    for first, last in sorted(found):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(last, merged[-1][1]))
        else:
            merged.append((first, last))
    return merged


def main(emoji_data, core_properties):
    tables = {
        "EXTENDED_PICTOGRAPHIC": ranges(emoji_data, "Extended_Pictographic"),
        "EMOJI_MODIFIER": ranges(emoji_data, "Emoji_Modifier"),
        "DEFAULT_IGNORABLE": ranges(core_properties, "Default_Ignorable_Code_Point"),
    }
    lines = [
        '"""Unicode 15.1 code point ranges for syncmily/text.py.',
        "",
        "Generated by scripts/gen_emoji_data.py from:",
        *(f"    {source}" for source in SOURCES),
        "Do not edit by hand: run the script again instead.",
        '"""',
        "",
    ]
    for name, table in tables.items():
        items = [f"(0x{first:04X}, 0x{last:04X})," for first, last in table]
        if len(items) == 1:
            # Black keeps a one-item tuple on one line.
            lines += [f"{name} = ({items[0]})", ""]
            continue
        lines += [f"{name} = (", *(f"    {item}" for item in items), ")", ""]
    OUT.write_text("\n".join(lines[:-1]) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({', '.join(f'{k}: {len(v)}' for k, v in tables.items())})")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("Usage: gen_emoji_data.py emoji-data.txt DerivedCoreProperties.txt")
    main(sys.argv[1], sys.argv[2])
